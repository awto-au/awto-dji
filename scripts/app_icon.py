#!/usr/bin/env python3
"""Generate the awto-dji app icon: the AWTO mark (box with ring on its top edge) with a
quadcopter line drawing inside. Rules from awto-apps docs/branding/README.md: red #DC0308 flat
full-bleed, white square-cornered lines, stroke 24 (box) / 22 (ring).

Writes app/awto_dji_app/assets/branding/icon.svg, icon.png (1024) and the Android launcher
PNGs (mipmap-*). Log: tmp/logs/app_icon.log.

Usage: python3 -I scripts/app_icon.py
"""
import os
import subprocess
import sys

import cairosvg

RED, WHITE = "#DC0308", "#FFFFFF"
# Quadcopter plan view: body at (CX, CY), rotors at +-DX, +-DY. Arms cross at the body.
CX, CY, DX, DY, ROTOR_R, BODY = 509, 624, 170, 125, 60, 96

SVG = f"""<svg width="1024" height="1024" viewBox="0 0 1024 1024" xmlns="http://www.w3.org/2000/svg">
  <!-- awto-dji app icon. Generated by scripts/app_icon.py. -->
  <rect width="1024" height="1024" fill="{RED}"/>
  <rect x="146" y="260" width="726" height="588" fill="none" stroke="{WHITE}" stroke-width="24"/>
  <circle cx="510" cy="260" r="121" fill="{RED}" stroke="{WHITE}" stroke-width="22"/>
  <g stroke="{WHITE}" stroke-width="24" fill="none">
    <line x1="{CX - DX}" y1="{CY - DY}" x2="{CX + DX}" y2="{CY + DY}"/>
    <line x1="{CX - DX}" y1="{CY + DY}" x2="{CX + DX}" y2="{CY - DY}"/>
  </g>
  <g fill="{RED}" stroke="{WHITE}" stroke-width="22">
    <circle cx="{CX - DX}" cy="{CY - DY}" r="{ROTOR_R}"/>
    <circle cx="{CX + DX}" cy="{CY - DY}" r="{ROTOR_R}"/>
    <circle cx="{CX - DX}" cy="{CY + DY}" r="{ROTOR_R}"/>
    <circle cx="{CX + DX}" cy="{CY + DY}" r="{ROTOR_R}"/>
  </g>
  <rect x="{CX - BODY // 2}" y="{CY - BODY // 2}" width="{BODY}" height="{BODY}" fill="{RED}" stroke="{WHITE}" stroke-width="24"/>
</svg>
"""

MIPMAPS = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def repo_root():
    return os.environ.get("AWTO_DJI_REPO") or subprocess.check_output(
        ["git", "rev-parse", "--show-toplevel"], text=True,
        cwd=os.path.dirname(os.path.abspath(__file__))).strip()


def main():
    root = repo_root()
    log_path = os.path.join(root, "tmp", "logs", "app_icon.log")
    os.makedirs(os.path.dirname(log_path), exist_ok=True)
    log = open(log_path, "w", buffering=1)

    def say(msg):
        print(msg)
        log.write(msg + "\n")

    app = os.path.join(root, "app", "awto_dji_app")
    brand = os.path.join(app, "assets", "branding")
    os.makedirs(brand, exist_ok=True)
    svg_path = os.path.join(brand, "icon.svg")
    with open(svg_path, "w") as f:
        f.write(SVG)
    say(f"wrote {svg_path}")

    data = SVG.encode()
    png_path = os.path.join(brand, "icon.png")
    cairosvg.svg2png(bytestring=data, write_to=png_path, output_width=1024, output_height=1024)
    say(f"wrote {png_path}")

    res = os.path.join(app, "android", "app", "src", "main", "res")
    for density, size in MIPMAPS.items():
        out = os.path.join(res, f"mipmap-{density}", "ic_launcher.png")
        cairosvg.svg2png(bytestring=data, write_to=out, output_width=size, output_height=size)
        say(f"wrote {out} ({size}px)")


if __name__ == "__main__":
    sys.exit(main())
