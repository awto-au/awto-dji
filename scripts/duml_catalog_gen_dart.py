#!/usr/bin/env python3
"""Generate the Dart DUML catalog binding from the canonical catalog (#102 step 1, codegen).

docs/data/duml-catalog.json -> app/packages/duml/lib/src/generated/catalog_data.dart
A pure-data const binding (no deps) so the hand-written catalog.dart can be migrated onto it
incrementally. Proves the canonical -> binding path; Python/Rust generators follow the same shape.

  python3 scripts/duml_catalog_gen_dart.py
"""
import json
import os

ROOT = os.environ.get("DJI_REPO") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CAT = os.path.join(ROOT, "docs", "data", "duml-catalog.json")
OUT = os.path.join(ROOT, "app", "packages", "duml", "lib", "src", "generated", "catalog_data.dart")


def dart_str(s):
    return "null" if s is None else "'" + str(s).replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def hexint(s):
    try:
        return str(int(s, 16))          # single 0xNN
    except (ValueError, TypeError):
        return "null"                   # blank, '?', or ambiguous multi-id (e.g. '0x05,06,07') -> unknown


def main():
    cat = json.load(open(CAT))
    L = ["// GENERATED by scripts/duml_catalog_gen_dart.py from docs/data/duml-catalog.json — do not edit.",
         f"// Canonical DUML command catalog (awto-dji #102). {cat['n_commands']} commands; schema {cat['schema']}.",
         "//",
         "// ignore_for_file: lines_longer_than_80_chars",
         "",
         "/// One DUML command from the canonical catalog. `cmdId` null = id not yet confirmed.",
         "class DumlCatalogEntry {",
         "  final int? cmdSet;",
         "  final int? cmdId;",
         "  final String? name;",
         "  final String? direction;",
         "  final List<String> sources; // origins that attest this command (apk, dll, ...)",
         "  const DumlCatalogEntry(this.cmdSet, this.cmdId, this.name, this.direction, this.sources);",
         "}",
         "",
         "/// CmdSet value -> name.",
         "const dumlCmdSets = <int, String>{"]
    for hx, nm in sorted(cat["cmdsets"].items(), key=lambda kv: int(kv[0], 16)):
        L.append(f"  {int(hx, 16)}: {dart_str(nm)},")
    L += ["};", "",
          "/// The canonical command catalog, generated from docs/data/duml-catalog.json.",
          "const dumlCatalog = <DumlCatalogEntry>["]
    for c in cat["commands"]:
        origins = sorted({s["origin"] for s in c.get("sources", [])})
        src = "[" + ", ".join(dart_str(o) for o in origins) + "]"
        L.append(f"  DumlCatalogEntry({hexint(c['cmdset'])}, {hexint(c['cmdid'])}, {dart_str(c['name'])}, {dart_str(c['direction'])}, {src}),")
    L += ["];", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L))
    print(f"generated {cat['n_commands']} entries -> {OUT}")


if __name__ == "__main__":
    main()
