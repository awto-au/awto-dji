#!/usr/bin/env python3
"""Regenerate duml_catalog.py from docs/data/apk-dynamic-cmdset-ids.tsv (the 723-command
facts table already extracted from the dynamically-unpacked APK - see
scripts/re/extract_apk_cmdset.py). Pure facts in, pure facts out: numeric cmdset/cmdid and
the command's own name, nothing from DJI's code/expression.

Run after apk-dynamic-cmdset-ids.tsv changes: python3 -I scripts/re/gen_duml_catalog.py
"""
import csv
import os
import subprocess


def repo_root():
    return os.environ.get("AWTO_DJI_REPO") or subprocess.check_output(
        ["git", "rev-parse", "--show-toplevel"], text=True,
        cwd=os.path.dirname(os.path.abspath(__file__))).strip()


def main():
    root = repo_root()
    tsv_path = os.path.join(root, "docs", "data", "apk-dynamic-cmdset-ids.tsv")
    out_path = os.path.join(root, "scripts", "re", "duml_catalog.py")

    rows = []
    with open(tsv_path, newline="") as f:
        reader = csv.reader(f, delimiter="\t")
        next(reader)  # header: cmdset_value cmdset_name cmdid_value cmdid_name
        for cmdset, cmdset_name, cmdid, cmdid_name in reader:
            rows.append((int(cmdset), cmdset_name, int(cmdid), cmdid_name))

    with open(out_path, "w") as f:
        f.write(
            '"""GENERATED by gen_duml_catalog.py from docs/data/apk-dynamic-cmdset-ids.tsv '
            '- do not edit by hand.\n\n'
            "Every (cmdset, cmdid) DUML command name known from the dynamically-unpacked "
            "APK. Payload layout is NOT known for most of these - duml_commands.py holds "
            "the few that have been reverse-engineered into a real struct; everything else "
            "here can only be sent with an explicit --payload (or none) via duml_cli.py.\n"
            '"""\n\n'
            "# name -> (cmd_set, cmd_id, cmdset_name)\n"
            "CATALOG = {\n"
        )
        seen = {}
        for cmdset, cmdset_name, cmdid, cmdid_name in sorted(rows):
            key = cmdid_name
            n = seen.get(key, 0)
            seen[key] = n + 1
            if n:
                key = f"{key}#{cmdset_name}"  # disambiguate name collisions across cmdsets
            f.write(f"    {key!r}: ({cmdset:#04x}, {cmdid:#04x}, {cmdset_name!r}),\n")
        f.write("}\n")

    print(f"wrote {len(rows)} commands to {out_path}")


if __name__ == "__main__":
    main()
