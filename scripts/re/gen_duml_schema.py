def command_fields(schema):
    return schema.get("fields", [])


def bit_mask(width):
    return (1 << width) - 1


def python_param_name(sub):
    return sub["name"]


def gen_python_command(schema, snake):
    class_name = schema["name"]
    primary = schema["ids"][0]
    fields = command_fields(schema)
    payload_len = schema["payload_length"]

    ctypes_fields = []
    init_params = []
    param_checks = []
    pack_lines = []  # computes each packed_u8 group's byte value before super().__init__
    super_kwargs = []

    for f in fields:
        kind = f["kind"]
        if kind == "packed_u8":
            ctypes_fields.append(f'("{f["name"]}", C.c_uint8),')
            parts = []
            for b in f["bits"]:
                name = python_param_name(b)
                default = b["default"]
                init_params.append(f'{name}={default!r}')
                if b.get("type") == "bool":
                    parts.append(f'(int(bool({name})) << {b["shift"]})')
                else:
                    valid = b.get("valid")
                    if valid:
                        param_checks.append(
                            f'        if {name} not in {tuple(valid)!r}:\n'
                            f'            raise ValueError(f"{name} must be one of {valid}, '
                            f'got {{{name}}}")')
                    parts.append(f'(({name} & {bit_mask(b["width"])}) << {b["shift"]})')
            pack_lines.append(f'        {f["name"]}_packed = {" | ".join(parts)}')
            super_kwargs.append(f'{f["name"]}={f["name"]}_packed')
        elif kind == "i16_scaled":
            ctypes_fields.append(f'("{f["name"]}", C.c_int16),')
            default = f["default"]
            init_params.append(f'{f["name"]}={default!r}')
            pack_lines.append(f'        {f["name"]}_raw = round({f["name"]} * {f["scale"]})')
            super_kwargs.append(f'{f["name"]}={f["name"]}_raw')
        elif f["role"] == "const":
            ctypes_fields.append(f'("{f["name"]}", {WIRE_TYPES[kind][0]}),')
            super_kwargs.append(f'{f["name"]}={f["value"]}')
        else:
            ctypes_fields.append(f'("{f["name"]}", {WIRE_TYPES[kind][0]}),')
            default = f["default"]
            init_params.append(f'{f["name"]}={default!r}')
            if f.get("valid"):
                valid = tuple(f["valid"])
                param_checks.append(
                    f'        if {f["name"]} not in {valid!r}:\n'
                    f'            raise ValueError(f"{f["name"]} must be one of {valid}, '
                    f'got {{{f["name"]}}}")')
            super_kwargs.append(f'{f["name"]}={f["name"]}')

    # decode(): read every field back out of a captured payload, for the pretty
    # printer (duml_telemetry.PUSH_DECODERS) - this is an outgoing command, but a
    # bus capture can still show one, so it still needs read-back for display.
    decode_lines = [f"    if len(payload) < {payload_len}:", "        return None", "    out = {}"]
    for f in fields:
        kind = f["kind"]
        if kind == "packed_u8":
            decode_lines.append(
                f'    _{f["name"]} = struct.unpack_from("B", payload, {f["offset"]})[0]')
            for b in f["bits"]:
                name = python_param_name(b)
                expr = f'(_{f["name"]} >> {b["shift"]}) & {bit_mask(b["width"])}'
                if b.get("type") == "bool":
                    expr = f'bool({expr})'
                decode_lines.append(f'    out["{name}"] = {expr}')
        elif kind == "i16_scaled":
            decode_lines.append(
                f'    out["{f["name"]}"] = struct.unpack_from("<h", payload, '
                f'{f["offset"]})[0] / {f["scale"]}')
        else:
            _, struct_code, _, _ = WIRE_TYPES[kind]
            decode_lines.append(
                f'    out["{f["name"]}"] = struct.unpack_from("{struct_code}", payload, '
                f'{f["offset"]})[0]')
    decode_lines.append("    return out")

    lines = [
        f'"""GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - '
        f'do not edit by hand.',
        "",
        f'{class_name} - {schema["class_doc"].strip()}'.replace("\n", " "),
        f'Confidence: {schema["confidence"]}. {schema["provenance"].strip()}'.replace("\n", " "),
        '"""',
        "import ctypes as C",
        "import struct",
        "",
        f"IDS = ((0x{primary['cmdset']:02x}, 0x{primary['cmdid']:02x}),)",
        f"CMD_SET = 0x{primary['cmdset']:02x}",
        f"CMD_ID = 0x{primary['cmdid']:02x}",
        f"PAYLOAD_LENGTH = {payload_len}",
        "",
        "",
        f"class {class_name}(C.LittleEndianStructure):",
        '    """Build the outgoing payload. bytes(instance) gives the raw bytes."""',
        '    _pack_ = 1',
        '    _fields_ = [',
        *[f'        {line}' for line in ctypes_fields],
        '    ]',
        "",
        f'    def __init__(self{", " + ", ".join(init_params) if init_params else ""}):',
        *param_checks,
        *pack_lines,
        f'        super().__init__({", ".join(super_kwargs)})',
        "",
        "",
        "def decode(payload):",
        f'    """Read {class_name}\'s fields back out of a captured payload (for display -',
        '    e.g. the pretty printer - not for building a new command, use the class above).',
        '    Returns None if the payload is too short."""',
        *decode_lines,
        "",
    ]
    return "\n".join(lines)


def dart_bit_type(sub):
    return "bool" if sub.get("type") == "bool" else "int"


def gen_dart_command(schema, snake):
    class_name = schema["name"]
    primary = schema["ids"][0]
    fields = command_fields(schema)
    payload_len = schema["payload_length"]

    decls = []
    ctor_params = []
    checks = []
    pack_lines = []  # computes each packed_u8 group's byte value, as a local in encodePayload
    set_calls = []

    for f in fields:
        kind = f["kind"]
        if kind == "packed_u8":
            parts = []
            for b in f["bits"]:
                name = dart_name(b)
                decls.append(f'  final {dart_bit_type(b)} {name};')
                default = str(b["default"]).lower() if b.get("type") == "bool" else b["default"]
                ctor_params.append(f'    this.{name} = {default},')
                if b.get("type") == "bool":
                    parts.append(f'((({name} ? 1 : 0)) << {b["shift"]})')
                else:
                    valid = b.get("valid")
                    if valid:
                        cond = " && ".join(f'{name} != {v}' for v in valid)
                        checks.append(
                            f'    if ({cond}) {{\n'
                            f'      throw ArgumentError(\'{b["name"]} must be one of {valid}, '
                            f'got $' + '{' + name + '}' + '\');\n'
                            f'    }}')
                    parts.append(f'(({name} & {bit_mask(b["width"])}) << {b["shift"]})')
            pack_lines.append(f'    final {dart_name(f)}Packed = {" | ".join(parts)};')
            set_calls.append(f'      ..setUint8({f["offset"]}, {dart_name(f)}Packed)')
        elif kind == "i16_scaled":
            name = dart_name(f)
            decls.append(f'  final double {name};')
            ctor_params.append(f'    this.{name} = {float(f["default"])},')
            pack_lines.append(f'    final {name}Raw = ({name} * {f["scale"]}).round();')
            set_calls.append(f'      ..setInt16({f["offset"]}, {name}Raw, Endian.little)')
        elif f["role"] == "const":
            _, _, suffix, size = WIRE_TYPES[kind]
            endian = ", Endian.little" if size > 1 else ""
            set_calls.append(f'      ..set{suffix}({f["offset"]}, {f["value"]}{endian})')
        else:
            name = dart_name(f)
            decls.append(f'  final int {name};')
            ctor_params.append(f'    this.{name} = {f["default"]},')
            valid = f.get("valid")
            if valid:
                cond = " && ".join(f'{name} != {v}' for v in valid)
                checks.append(
                    f'    if ({cond}) {{\n'
                    f'      throw ArgumentError(\'{f["name"]} must be one of {valid}, '
                    f'got $' + '{' + name + '}' + '\');\n'
                    f'    }}')
            _, _, suffix, size = WIRE_TYPES[kind]
            endian = ", Endian.little" if size > 1 else ""
            set_calls.append(f'      ..set{suffix}({f["offset"]}, {name}{endian})')

    ctor_body = f'''{{
{chr(10).join(checks)}
  }}''' if checks else ''
    param_block = (f'{{\n{chr(10).join(ctor_params)}\n  }}' if ctor_params else '')

    payload_body = (
        f'{chr(10).join(pack_lines)}\n'
        f'    final payload = ByteData({payload_len})\n'
        f'{chr(10).join(set_calls)};\n'
        f'    return payload.buffer.asUint8List();'
        if fields else
        f'    return Uint8List({payload_len});'
    )

    out = f'''// GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - do not
// edit by hand. Regenerate: python3 -I scripts/re/gen_duml_schema.py
//
// {schema["class_doc"].strip().replace(chr(10), " ")}
// Confidence: {schema["confidence"]}.
// {schema["provenance"].strip().replace(chr(10), " ")}
//
// Generic command: pass whichever receiverType the call site targets (FC, gimbal,
// camera, RC, ...) - not baked into this class.
library;

import 'dart:typed_data';

import '../packet.dart';

class {class_name} {{
  static const int cmdSet = 0x{primary["cmdset"]:02x};
  static const int cmdId = 0x{primary["cmdid"]:02x};

{chr(10).join(decls)}

  {class_name}({param_block}){ctor_body}{';' if not ctor_body else ''}

  /// Raw {payload_len}-byte payload for this command, independent of sender/receiver.
  Uint8List encodePayload() {{
{payload_body}
  }}

  /// Full packet bytes, ready to send.
  Uint8List encode({{
    required int receiverType,
    int senderType = DeviceType.app,
    required int sequence,
    AckType ackType = AckType.afterExec,
  }}) {{
    return DumlPacket(
      senderType: senderType,
      receiverType: receiverType,
      sequence: sequence,
      ackType: ackType,
      cmdSet: cmdSet,
      cmdId: cmdId,
      payload: encodePayload(),
    ).encode();
  }}
}}
'''
    return out


