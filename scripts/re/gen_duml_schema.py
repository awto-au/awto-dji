def main():
    root = Path(repo_root())
    schema_dir = root / "docs" / "schema" / "duml"
    schema_path = schema_dir / "commands.yaml"
    py_out_dir = root / "scripts" / "re" / "duml_generated"
    dart_out_dir = root / "app" / "packages" / "duml" / "lib" / "src" / "generated"
    dart_test_dir = root / "app" / "packages" / "duml" / "test" / "generated"
    doc_out_dir = schema_dir / "generated"
    for d in (py_out_dir, dart_out_dir, dart_test_dir, doc_out_dir):
        d.mkdir(parents=True, exist_ok=True)
    (py_out_dir / "__init__.py").touch()

    all_entries = yaml.safe_load(schema_path.read_text())

    count = 0
    for duml_code, schema in sorted(all_entries.items()):
        snake = snake_case(schema["name"])
        direction = schema.get("direction", "push")

        if direction == "push":
            py_src = gen_python_push(schema, snake)
            dart_src = gen_dart_push(schema, snake)
        elif direction == "command":
            py_src = gen_python_command(schema, snake)
            dart_src = gen_dart_command(schema, snake)
        else:
            raise ValueError(f"{duml_code}: unknown direction {direction!r}")

        (py_out_dir / f"{snake}.py").write_text(py_src)
        dart_path = dart_out_dir / f"{snake}.dart"
        dart_path.write_text(dart_src)
        subprocess.run(["dart", "format", str(dart_path)], check=True)

        py_test_src = gen_python_tests(schema, snake)
        if py_test_src:
            (py_out_dir / f"test_{snake}.py").write_text(py_test_src)

        dart_test_src = gen_dart_tests(schema, snake)
        if dart_test_src:
            dart_test_path = dart_test_dir / f"{snake}_test.dart"
            dart_test_path.write_text(dart_test_src)
            subprocess.run(["dart", "format", str(dart_test_path)], check=True)

        doc_path = doc_out_dir / f"{snake}.md"
        doc_path.write_text(gen_markdown(schema, snake))

        log(f"generated {duml_code} {snake}: py+dart code, "
            f"{'py+dart tests, ' if py_test_src else ''}doc")
        count += 1

    log(f"done: {count} entries processed from {schema_path.relative_to(root)}")


if __name__ == "__main__":
    main()
