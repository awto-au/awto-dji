#!/usr/bin/env python3
"""Generate language code, tests and docs from docs/schema/duml/commands.yaml - the
canonical DUML command/field schema (awto-dji#33). One file, one map, keyed by DUML
code ("0xSS/0xII", the primary cmdset/cmdid). See docs/schema/duml/README.md for
scope and field format.

Two schema `direction`s:
  push    - decode-only (an incoming telemetry push). OsdGeneral is the PoC.
  command - encode-only (an outgoing command). RestartDevice was the first.

Emits, per entry (file name = snake_case of the entry's `name`):
  scripts/re/duml_generated/<name>.py
  app/packages/duml/lib/src/generated/<name>.dart
  scripts/re/duml_generated/test_<name>.py        (if the entry has `tests:`)
  app/packages/duml/test/generated/<name>_test.dart  (if the entry has `tests:`)
  docs/schema/duml/generated/<name>.md            (always - the human-readable doc)

Run after any .yaml change: python3 -I scripts/re/gen_duml_schema.py
"""
import os
import subprocess
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from _log import log  # noqa: E402

DEG_PER_RAD_DART = "180.0 / math.pi"
DEG_PER_RAD_PY = "180.0 / math.pi"

# ctypes/struct type -> (python ctypes type, struct.pack code, dart ByteData suffix, size)
WIRE_TYPES = {
    "u8": ("C.c_uint8", "B", "Uint8", 1),
    "u16": ("C.c_uint16", "<H", "Uint16", 2),
    "u32": ("C.c_uint32", "<I", "Uint32", 4),
    "i16": ("C.c_int16", "<h", "Int16", 2),
}


def repo_root():
    return os.environ.get("AWTO_DJI_REPO") or subprocess.check_output(
        ["git", "rev-parse", "--show-toplevel"], text=True,
        cwd=os.path.dirname(os.path.abspath(__file__))).strip()


def camel(snake):
    head, *rest = snake.split("_")
    return head + "".join(w.capitalize() for w in rest)


def snake_case(name):
    """CamelCase class name -> snake_case file stem, e.g. RestartDevice -> restart_device."""
    import re as _re
    return _re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def dart_name(field):
    return field.get("dart_name") or camel(field["name"])


def dart_type(field):
    kind = field["kind"]
    if kind in ("enum_u8", "motor_failed_cause_p3"):
        return field["enum_ref"]
    return {
        "f64_rad_to_deg": "double",
        "i16_scaled": "double",
        "u8": "int",
        "u16": "int",
        "u32": "int",
        "i16": "int",
        "i8": "int",
        "bitfield_u32": "bool",
        "bitfield_u8": "bool",
        "bits_u8": "int",
        "ascii_nul": "String",
        "version_quad": "String",
    }[kind]


def is_optional(field, base_min_length):
    return field.get("min_length", base_min_length) > base_min_length


# ============================================================================
# direction: push (decode) - unchanged from the OsdGeneral PoC
# ============================================================================

PY_EXPR = {
    "f64_rad_to_deg": lambda f: f'struct.unpack_from("<d", payload, {f["offset"]})[0] * {DEG_PER_RAD_PY}',
    "i16_scaled": lambda f: f'struct.unpack_from("<h", payload, {f["offset"]})[0] / {f["scale"]}',
    "u8": lambda f: f'payload[{f["offset"]}]',
    "i8": lambda f: f'struct.unpack_from("<b", payload, {f["offset"]})[0]',
    "bitfield_u8": lambda f: f'bool((payload[{f["offset"]}] >> {f["bit"]}) & 1)',
    "bits_u8": lambda f: f'(payload[{f["offset"]}] >> {f["shift"]}) & {bit_mask(f["width"])}',
    "ascii_nul": lambda f: (
        f'payload[{f["offset"]}:{f["offset"]}+{f["length"]}].split(b"\\x00", 1)[0]'
        f'.decode("ascii", "replace")'
    ),
    "version_quad": lambda f: (
        f'".".join(f"{{b:02d}}" for b in reversed(payload[{f["offset"]}:{f["offset"]}+4]))'
    ),
    "bitfield_u32": lambda f: (
        f'bool((struct.unpack_from("<I", payload, {f["offset"]})[0] >> {f["bit"]}) & 1)'
    ),
}


def gen_python_push(schema, snake):
    base_min = schema["min_length"]
    py_fields = [f for f in schema["fields"] if "python" in f["targets"]]
    for f in py_fields:
        if f["kind"] not in PY_EXPR:
            raise ValueError(f"field {f['name']!r}: kind {f['kind']!r} has no Python codegen "
                              f"({sorted(PY_EXPR)} do) - remove 'python' from "
                              f"its targets or extend gen_duml_schema.py")
        if is_optional(f, base_min):
            raise ValueError(f"field {f['name']!r}: python target does not support per-field "
                              f"min_length > schema min_length ({base_min}) yet")

    ids = ", ".join(f'(0x{i["cmdset"]:02x}, 0x{i["cmdid"]:02x})' for i in schema["ids"])
    lines = [
        f'"""GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - '
        f'do not edit by hand.',
        "",
        f'{schema["name"]} - {schema["class_doc"].strip()}'.replace("\n", " "),
        f'Confidence: {schema["confidence"]}. {schema["provenance"].strip()}'.replace("\n", " "),
        '"""',
        "import math",
        "import struct",
        "",
        f"IDS = ({ids},)",
        f"MIN_LENGTH = {base_min}",
        "",
        "",
        "def decode(payload):",
        f'    """Returns a dict of {[f["name"] for f in py_fields]}, or None if the payload',
        '    is too short to be this push."""',
        f"    if len(payload) < MIN_LENGTH:",
        "        return None",
        "    return {",
    ]
    for f in py_fields:
        lines.append(f'        {f["name"]!r}: {PY_EXPR[f["kind"]](f)},')
    lines += ["    }", ""]
    return "\n".join(lines)


def dart_required_expr(f):
    kind = f["kind"]
    off = f["offset"]
    if kind == "f64_rad_to_deg":
        return f'd.getFloat64({off}, Endian.little) * degPerRad'
    if kind == "i16_scaled":
        return f'd.getInt16({off}, Endian.little) / {f["scale"]}.0'
    if kind == "u8":
        return f'd.getUint8({off})'
    if kind == "i8":
        return f'd.getInt8({off})'
    if kind == "bitfield_u8":
        return f'(d.getUint8({off}) >> {f["bit"]}) & 1 != 0'
    if kind == "bits_u8":
        return f'(d.getUint8({off}) >> {f["shift"]}) & {bit_mask(f["width"])}'
    if kind == "ascii_nul":
        length = f["length"]
        return (f'(() {{ final bytes = payload.sublist({off}, {off} + {length}); '
                f'final nul = bytes.indexOf(0); '
                f'return String.fromCharCodes(nul >= 0 ? bytes.sublist(0, nul) : bytes); }})()')
    if kind == "version_quad":
        return (f'[for (var i = {off} + 3; i >= {off}; i--) d.getUint8(i)]'
                f'.map((b) => b.toString().padLeft(2, \'0\')).join(\'.\')')
    if kind == "bitfield_u32":
        return f'(d.getUint32({off}, Endian.little) >> {f["bit"]}) & 1 != 0'
    raise ValueError(f"kind {kind} cannot be a required (non-optional) field")


def dart_motor_failed_cause_block(f, flyc_var):
    off, alt, enum_ref = f["byte_offset"], f["alt_byte_offset"], f["enum_ref"]
    name = dart_name(f)
    return (
        f"    // offset {off}: 1 byte -> needs length >= {f['min_length']} (+ offset {alt} for\n"
        f"    // the pre-flycVersion-26 no-start-action case).\n"
        f"    if (payload.length >= {f['min_length']} && {flyc_var} != null) {{\n"
        f"      final raw{off} = d.getUint8({off});\n"
        f"      if ({flyc_var} >= 26) {{\n"
        f"        {name} = {enum_ref}.find(raw{off});\n"
        f"      }} else if ((raw{off} >> 7) == 0) {{\n"
        f"        {name} = {enum_ref}.none;\n"
        f"      }} else if (payload.length <= {alt}) {{\n"
        f"        {name} = {enum_ref}.find(raw{off} & 0x7f);\n"
        f"      }} else {{\n"
        f"        {name} = {enum_ref}.find(d.getUint8({alt}) & 0xff);\n"
        f"      }}\n"
        f"    }}\n"
    )


def gen_dart_push(schema, snake):
    base_min = schema["min_length"]
    fields = [f for f in schema["fields"] if "dart" in f["targets"]]
    required = [f for f in fields if not is_optional(f, base_min)]
    optional = [f for f in fields if is_optional(f, base_min)]

    class_name = schema["name"]
    ids = schema["ids"]
    primary, aliases = ids[0], ids[1:]

    field_name_by_schema_name = {f["name"]: dart_name(f) for f in fields}

    decls = []
    ctor_params = []
    for f in required:
        decls.append(f'  final {dart_type(f)} {dart_name(f)};')
        ctor_params.append(f'required this.{dart_name(f)},')
    for f in optional:
        decls.append(f'  final {dart_type(f)}? {dart_name(f)};')
        ctor_params.append(f'this.{dart_name(f)},')

    bitfield_groups = {}
    for f in optional:
        if f["kind"] == "bitfield_u32":
            bitfield_groups.setdefault((f["offset"], f["min_length"]), []).append(f)

    body_lines = []
    emitted_groups = set()
    for f in optional:
        if f["kind"] == "u8":
            body_lines.append(
                f'    // offset {f["offset"]}: 1 byte -> needs length >= {f["min_length"]}.')
            body_lines.append(
                f'    if (payload.length >= {f["min_length"]}) '
                f'{dart_name(f)} = d.getUint8({f["offset"]});')
        elif f["kind"] == "bitfield_u32":
            key = (f["offset"], f["min_length"])
            if key in emitted_groups:
                continue
            emitted_groups.add(key)
            offset, min_len = key
            body_lines.append(f'    // offset {offset}: 4-byte flags int -> needs length '
                               f'>= {min_len}.')
            body_lines.append(f'    if (payload.length >= {min_len}) {{')
            body_lines.append(f'      final flags{offset} = '
                               f'd.getUint32({offset}, Endian.little);')
            for g in bitfield_groups[key]:
                body_lines.append(f'      {dart_name(g)} = '
                                   f'(flags{offset} >> {g["bit"]}) & 1 != 0;')
            body_lines.append('    }')
        elif f["kind"] == "enum_u8":
            body_lines.append(
                f'    if (payload.length >= {f["min_length"]}) '
                f'{dart_name(f)} = {f["enum_ref"]}.find(d.getUint8({f["offset"]}));')
        elif f["kind"] == "motor_failed_cause_p3":
            flyc_var = field_name_by_schema_name[f["flyc_version_field"]]
            body_lines.append(dart_motor_failed_cause_block(f, flyc_var).rstrip())
        else:
            raise ValueError(f"field {f['name']!r}: kind {f['kind']!r} has no Dart codegen")

    return_fields = ",\n      ".join(
        [f'{dart_name(f)}: {dart_required_expr(f)}' for f in required] +
        [f'{dart_name(f)}: {dart_name(f)}' for f in optional]
    )

    optional_decls = "\n".join(f"    {dart_type(f)}? {dart_name(f)};" for f in optional)

    alias_checks = " ||\n          ".join(
        [f'(p.cmdSet == 0x{primary["cmdset"]:02x} && p.cmdId == 0x{primary["cmdid"]:02x})'] +
        [f'(p.cmdSet == 0x{a["cmdset"]:02x} && p.cmdId == 0x{a["cmdid"]:02x})' for a in aliases]
    )

    # Keep unused imports/locals out of generated files - most push schemas don't
    # need radians or the motor_status enums, and an unused import/var fails
    # `dart analyze` under this project's lint config.
    needs_deg_per_rad = any(f["kind"] == "f64_rad_to_deg" for f in fields)
    needs_motor_status = any(f["kind"] in ("enum_u8", "motor_failed_cause_p3") for f in fields)
    math_import = "import 'dart:math' as math;\n" if needs_deg_per_rad else ""
    motor_status_import = "import '../motor_status.dart';\n" if needs_motor_status else ""
    deg_per_rad_decl = f"    const degPerRad = {DEG_PER_RAD_DART};\n" if needs_deg_per_rad else ""

    out = f'''// GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - do not
// edit by hand. Regenerate: python3 -I scripts/re/gen_duml_schema.py
//
// {schema["class_doc"].strip().replace(chr(10), " ")}
// Confidence: {schema["confidence"]}.
// {schema["provenance"].strip().replace(chr(10), " ")}
library;

{math_import}import 'dart:typed_data';

{motor_status_import}import '../packet.dart';

class {class_name} {{
{chr(10).join(decls)}

  {class_name}({{
{chr(10).join("    " + p for p in ctor_params)}
  }});

  static const int cmdSet = 0x{primary["cmdset"]:02x};
  static const int cmdId = 0x{primary["cmdid"]:02x};

  /// True if `p` is a {class_name} push this decoder understands - matches any of
  /// the cmdset/cmdid pairs this struct is registered under (see schema `ids`).
  static bool matches(DumlPacket p) =>
      ({alias_checks}) &&
      p.payload.length >= {base_min};

  /// Decode from a packet, or return null if it is not a {class_name} push.
  static {class_name}? fromPacket(DumlPacket p) {{
    if (!matches(p)) return null;
    return fromPayload(p.payload);
  }}

  static {class_name} fromPayload(Uint8List payload) {{
    final d = ByteData.sublistView(payload);
{deg_per_rad_decl}
{optional_decls}

{chr(10).join(body_lines)}

    return {class_name}(
      {return_fields},
    );
  }}
}}
'''
    return out


