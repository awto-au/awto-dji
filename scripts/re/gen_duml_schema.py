# Tests (both directions, only when the schema has a `tests:` list)
# ============================================================================

def gen_python_tests(schema, snake):
    if "tests" not in schema:
        return None
    class_name = schema["name"]
    cases = []
    for t in schema["tests"]:
        if schema.get("direction", "push") == "command":
            params = ", ".join(f'{k}={v!r}' for k, v in t.get("params", {}).items())
            if t.get("expect_error"):
                cases.append(
                    f'def test_{t["name"]}():\n'
                    f'    with pytest.raises(ValueError):\n'
                    f'        {class_name}({params})\n')
            else:
                expect = t["expect_payload_hex"]
                cases.append(
                    f'def test_{t["name"]}():\n'
                    f'    c = {class_name}({params})\n'
                    f'    assert bytes(c).hex() == {expect!r}\n')
    if not cases:
        return None
    lines = [
        f'"""GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - '
        f'do not edit by hand."""',
        "import pytest",
        "",
        f"from duml_generated.{snake} import {class_name}",
        "",
        "",
        *cases,
    ]
    return "\n".join(lines)


def gen_dart_tests(schema, snake):
    if "tests" not in schema:
        return None
    class_name = schema["name"]
    cases = []
    for t in schema["tests"]:
        if schema.get("direction", "push") == "command":
            params = ", ".join(f'{camel(k)}: {v}' for k, v in t.get("params", {}).items())
            if t.get("expect_error"):
                cases.append(
                    f"  test('{t['name']}', () {{\n"
                    f"    expect(() => {class_name}({params}), throwsArgumentError);\n"
                    f"  }});\n")
            else:
                expect = t["expect_payload_hex"]
                bytes_list = ", ".join(f'0x{expect[i:i+2]}' for i in range(0, len(expect), 2))
                cases.append(
                    f"  test('{t['name']}', () {{\n"
                    f"    final c = {class_name}({params});\n"
                    f"    expect(c.encodePayload(), equals([{bytes_list}]));\n"
                    f"  }});\n")
    if not cases:
        return None
    out = (
        f"// GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - do not\n"
        f"// edit by hand.\n"
        f"import 'package:duml/duml.dart';\n"
        f"import 'package:test/test.dart';\n\n"
        f"void main() {{\n"
        f"  group('{class_name} (generated)', () {{\n"
        f"{chr(10).join(cases)}"
        f"  }});\n"
        f"}}\n"
    )
    return out


