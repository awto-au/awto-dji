# Docs (both directions) - the canonical human-readable page per command
# ============================================================================

def gen_markdown(schema, snake):
    direction = schema.get("direction", "push")
    lines = [
        f'<!-- GENERATED by gen_duml_schema.py from docs/schema/duml/commands.yaml - '
        f'do not edit by hand. Edit the YAML and regenerate. -->',
        "",
        f'# {schema["name"]} ({direction})',
        "",
        schema["class_doc"].strip(),
        "",
        f'**Confidence:** {schema["confidence"]}',
        "",
        f'**Provenance:** {schema["provenance"].strip()}',
        "",
        "## IDs",
        "",
        "| cmdset | cmdid | name |",
        "|---|---|---|",
    ]
    for i in schema["ids"]:
        lines.append(f'| 0x{i["cmdset"]:02x} | 0x{i["cmdid"]:02x} | {i.get("catalog_name", "")} |')
    lines += ["", "## Fields", "", "| name | offset | kind | role/default/valid | confidence | doc |",
              "|---|---|---|---|---|---|"]
    for f in schema.get("fields", []):
        kind = f["kind"]
        if kind == "packed_u8":
            bits_desc = "; ".join(
                f'{b["name"]}@bit{b["shift"]}(w{b.get("width", 1)}, default={b["default"]})'
                for b in f["bits"])
            lines.append(f'| {f["name"]} | {f.get("offset", "")} | {kind} | {bits_desc} | | '
                         f'{f.get("doc", "").strip()} |')
            continue
        if direction == "command":
            if kind == "i16_scaled":
                rdv = f'default={f["default"]}, scale={f["scale"]}'
            elif f["role"] == "const":
                rdv = f'const={f["value"]}'
            else:
                rdv = f'default={f["default"]}' + (f', valid={f.get("valid")}' if f.get("valid") else '')
        else:
            rdv = f'scale={f.get("scale")}' if f.get("scale") else ''
        lines.append(f'| {f["name"]} | {f.get("offset", "")} | {kind} | {rdv} | '
                     f'{f.get("confidence", "")} | {f.get("doc", "").strip()} |')
    if "tests" in schema:
        lines += ["", "## Test vectors", "", "| name | doc |", "|---|---|"]
        for t in schema["tests"]:
            lines.append(f'| {t["name"]} | {t.get("doc", "").strip()} |')
    lines.append("")
    return "\n".join(lines)


